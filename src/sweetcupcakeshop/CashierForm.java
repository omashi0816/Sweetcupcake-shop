    private void btnAddSellActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddSellActionPerformed
        // TODO add your handling code here:\
        String name = txtName.getText();
        String priceText = txtPrice.getText();
        String qtyText = txtQty.getText();
        String totalText = txtTotal.getText();

        if (name.isEmpty() || priceText.isEmpty() || qtyText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields!");
            return;
        }

        try {
            double price = Double.parseDouble(priceText);
            int qty = Integer.parseInt(qtyText);
            double total = Double.parseDouble(totalText);

            DefaultTableModel model = (DefaultTableModel) tblCupcakes.getModel();
            model.addRow(new Object[]{name, price, total}); // store total in table

            // Clear fields
            txtName.setText("");
            txtPrice.setText("");
            txtQty.setText("");
            txtTotal.setText("0");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Enter valid numbers!");
        }
    }//GEN-LAST:event_btnAddSellActionPerformed

