    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        String name = txtName.getText();
        String priceText = txtPrice.getText();

        if (name.isEmpty() || priceText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields!");
            return;
        }

        try {
            double price = Double.parseDouble(priceText);

            // 1. Add to DataStore
            Cupcake cupcake = new Cupcake(name, price);
            DataStore.cupcakes.add(cupcake);

            // 2. Add to manager table
            DefaultTableModel model = (DefaultTableModel) tblCupcakes.getModel();
            model.addRow(new Object[]{name, price});

            // Clear fields
            txtName.setText("");
            txtPrice.setText("");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Enter a valid price!");
        }
    }//GEN-LAST:event_btnAddActionPerformed

    
    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        DefaultTableModel model = (DefaultTableModel) tblCupcakes.getModel();
    int selectedRow = tblCupcakes.getSelectedRow();

        if (selectedRow >= 0) {
        // Remove from DataStore
        DataStore.cupcakes.remove(selectedRow);
        // Remove from table
        model.removeRow(selectedRow);
        } else {
            JOptionPane.showMessageDialog(this, "Select a row to delete!");
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        DefaultTableModel model = (DefaultTableModel) tblCupcakes.getModel();
        int selectedRow = tblCupcakes.getSelectedRow();

        if (selectedRow >= 0) {
        String newName = txtName.getText();
        String newPriceText = txtPrice.getText();

        if (newName.isEmpty() || newPriceText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please fill all fields!");
            return;
        }

        try {
            double newPrice = Double.parseDouble(newPriceText);

            // Update DataStore
            Cupcake cupcake = DataStore.cupcakes.get(selectedRow);
            cupcake.setName(newName);
            cupcake.setPrice(newPrice);

            // Update table
            model.setValueAt(newName, selectedRow, 0);
            model.setValueAt(newPrice, selectedRow, 1);

            txtName.setText("");
            txtPrice.setText("");

            JOptionPane.showMessageDialog(this, "Cupcake updated successfully!");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Enter a valid price!");
        }
       }
    }//GEN-LAST:event_btnUpdateActionPerformed

